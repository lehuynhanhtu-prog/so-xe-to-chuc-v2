test('bundled AES-GCM ciphertext agrees with Node crypto and PBKDF2 agrees at 600000 rounds',()=>{
  const crypto=require('node:crypto');const lib=Function(fs.readFileSync('apps-script/Crypto.gs','utf8')+';return DriveCrypto;')();
  const key=crypto.randomBytes(32),nonce=crypto.randomBytes(12),aad=Buffer.from('so-xe-drive-v2'),plain=Buffer.from('Tên tổ chức — UTF-8');
  const cipher=crypto.createCipheriv('aes-256-gcm',key,nonce);cipher.setAAD(aad);
  const expected=Buffer.concat([cipher.update(plain),cipher.final(),cipher.getAuthTag()]);
  assert.deepEqual(Buffer.from(lib.gcm(key,nonce,aad).encrypt(plain)),expected);
  const salt=crypto.randomBytes(16),password=Buffer.from('Vietnamese mật khẩu');
  assert.deepEqual(Buffer.from(lib.pbkdf2(lib.sha256,password,salt,{c:600000,dkLen:32})),crypto.pbkdf2Sync(password,salt,600000,32,'sha256'));
});
